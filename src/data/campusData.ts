// Helper: build a rectangular footprint around an exact coordinate
function footprintAround(
  lat: number,
  lng: number,
  wMeters: number,
  hMeters: number
) {
  const dLat = hMeters / 2 / 111_000;
  const dLng = wMeters / 2 / (111_000 * Math.cos((lat * Math.PI) / 180));
  return [
    { lat: lat - dLat, lng: lng - dLng },
    { lat: lat - dLat, lng: lng + dLng },
    { lat: lat + dLat, lng: lng + dLng },
    { lat: lat + dLat, lng: lng - dLng },
  ];
}

